-- Full name and mobile number on POST /auth/request-code.
--
-- The account is created when the code is redeemed (/auth/verify), not when
-- it is requested, so the details travel on the code row until then.
--
-- Rules:
--   • Both optional. Sign-in and sign-up are one flow, and a returning user
--     signing in on a new phone has no reason to type them again.
--   • Applied ONLY when redemption creates the account. An existing account's
--     name and phone are never changed here: anybody can type somebody else's
--     email into the request form.
--   • The phone is stored unverified (phone_verified_at stays NULL). This flow
--     proves the email, nothing else.
--   • Cleared from the code row on redemption, so personal data does not sit
--     in email_otps until the sweep.
--
-- Columns generated by drizzle-kit; the functions below are hand-written.
ALTER TABLE "email_otps" ADD COLUMN "name" varchar(200);--> statement-breakpoint
ALTER TABLE "email_otps" ADD COLUMN "phone" varchar(32);--> statement-breakpoint

-- New signature, so the old one is dropped rather than left as an overload.
DROP FUNCTION app_issue_email_code(citext, varchar, varchar, int);--> statement-breakpoint

CREATE FUNCTION app_issue_email_code(
  p_email       citext,
  p_code_hash   varchar,
  p_ip_hash     varchar,
  p_ttl_seconds int,
  p_name        varchar DEFAULT NULL,
  p_phone       varchar DEFAULT NULL
) RETURNS void
  LANGUAGE plpgsql VOLATILE SECURITY DEFINER
  SET search_path = public, pg_temp
AS $$
BEGIN
  UPDATE email_otps
     SET consumed_at = now(), name = NULL, phone = NULL
   WHERE email = p_email AND consumed_at IS NULL;

  INSERT INTO email_otps (id, email, code_hash, ip_hash, expires_at, name, phone)
  VALUES (uuid_generate_v7(), p_email, p_code_hash, p_ip_hash,
          now() + make_interval(secs => p_ttl_seconds), p_name, p_phone);
END;
$$;--> statement-breakpoint

