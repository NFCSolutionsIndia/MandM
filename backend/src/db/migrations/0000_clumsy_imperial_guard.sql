-- Hand-written, prepended to the generated migration. drizzle-kit emits table
-- DDL and does not model extensions or trigger functions, so anything the
-- schema depends on has to be stated here.
--
-- These live in the migration rather than in the Docker init script on purpose:
-- the migration pipeline must be the ONLY thing that defines a database. If
-- Docker installed citext, a Docker-built database and a migration-built
-- database would differ — and that difference would surface only where Docker
-- never runs, which is production.

-- Case-insensitive text, for `users.email`. PostgreSQL compares text
-- case-sensitively, which is right nearly everywhere and wrong for an address:
-- Aarav@x.com and aarav@x.com are one account, and a user who signs up twice
-- ends up with two archives and can find neither.
CREATE EXTENSION IF NOT EXISTS citext;
--> statement-breakpoint

-- `updated_at`, maintained by the database.
--
-- Drizzle's $onUpdate covers writes that go through the ORM. It does not cover
-- raw SQL, a migration backfill, or a hand-run UPDATE in psql — so this trigger
-- is the actual guarantee and the ORM hook is the convenience.
--
-- Defined now, used from the tenancy domain onward: no table in this migration
-- carries updated_at, but every later migration that adds one attaches this
-- rather than redefining it.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
