import { sql } from 'drizzle-orm';
import { v7 as uuidv7 } from 'uuid';
import {
  customType,
  date,
  index,
  timestamp,
  uuid,
  varchar,
  type AnyPgColumn,
} from 'drizzle-orm/pg-core';

/**
 * The sanctioned column helpers.
 *
 * Every table in this schema uses these rather than raw Drizzle types. That is
 * not style: each one exists because the obvious choice is wrong for this
 * product in a way that only shows up late, and a helper makes the safe thing
 * also the easy thing.
 *
 * Thirty-eight tables will import this file. A rule enforced here is a rule
 * nobody has to remember thirty-eight times.
 */

// ─── Identifiers ─────────────────────────────────────────────────────────────

/**
 * Primary key: a native `uuid`, generated by the application as **UUIDv7**.
 *
 * Why not `serial`/`bigserial`: an auto-incrementing key leaks how many rows
 * exist and lets anyone guess a neighbouring id. For a product holding private
 * family media, a guessable identifier is a privacy problem, not a style one.
 *
 * Why not UUIDv4: v4 is random throughout, so every insert lands in a random
 * page of the index and fragments it. **UUIDv7 carries a 48-bit big-endian
 * timestamp in its leading bytes**, so new keys sort to the right-hand edge of
 * the B-tree and inserts stay sequential. This schema inserts constantly —
 * memories, jobs, delivery attempts, audit rows — so the difference compounds.
 *
 * Generated in the application rather than by the database, which lets the
 * mobile apps mint an id offline and send it with the row, so a memory captured
 * on a plane already has its final identity.
 */
export function uuidPk(name = 'id') {
  return uuid(name)
    .primaryKey()
    .notNull()
    /**
     * `$defaultFn`, not a database `DEFAULT`.
     *
     * The value is generated in this process before the INSERT is sent, which
     * is what lets a mobile app mint an id offline and send it with the row —
     * so a memory captured on a plane already has its final identity, and the
     * retry when the connection returns is idempotent rather than a duplicate.
     *
     * It emits no DDL, so adding it changes no migration.
     */
    .$defaultFn(() => uuidv7());
}

/** A reference to another row's id. Nullability is decided per column. */
export function uuidRef(name: string) {
  return uuid(name);
}

// ─── Case-insensitive text ───────────────────────────────────────────────────

/**
 * `citext` — case-insensitive text, used for email.
 *
 * PostgreSQL compares text case-SENSITIVELY, which is right nearly everywhere
 * and wrong for an email address: `Aarav@x.com` and `aarav@x.com` are the same
 * account, and a user who ends up with two archives can find neither.
 *
 * Requires `CREATE EXTENSION citext`, installed by migration 0000.
 */
export const citext = customType<{ data: string; driverData: string }>({
  dataType: () => 'citext',
});

// ─── Time ────────────────────────────────────────────────────────────────────

/**
 * ═══════════════════════════════════════════════════════════════════════════
 *  THE ONLY SANCTIONED WAY TO DECLARE A TEMPORAL COLUMN.
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * `timestamptz`, millisecond precision, always.
 *
 * `timestamp without time zone` — the type you get from a bare `timestamp()` —
 * silently discards the offset. This product delivers a message into a
 * recipient's local morning on a date that may be twenty years away, so a
 * dropped offset is a delivery into the wrong hour that nobody discovers until
 * it happens. There is no later test that catches it.
 *
 * Millisecond precision rather than the default microseconds because that is
 * what JavaScript's `Date` carries; storing more precision than the application
 * can represent invites round-trip mismatches in tests.
 */
export function utcTimestamp(name: string) {
  return timestamp(name, { withTimezone: true, precision: 3, mode: 'date' });
}

/** `created_at`, defaulted by the database for rows the application forgets. */
export function createdAt(name = 'created_at') {
  return utcTimestamp(name)
    .notNull()
    .default(sql`now()`);
}

/**
 * `updated_at`.
 *
 * `$onUpdate` covers every write that goes through Drizzle. It does NOT cover
 * raw SQL, a migration backfill, or a hand-run `UPDATE` in psql — so a
 * `set_updated_at` trigger in migration 0000 is the real guarantee and this is
 * the convenience. The trigger is the boundary; the ORM hook is ergonomics.
 */
export function updatedAt(name = 'updated_at') {
  return utcTimestamp(name)
    .notNull()
    .default(sql`now()`)
    .$onUpdate(() => new Date());
}

/**
 * A calendar date with no time and no zone — a birthday, an anniversary.
 *
 * The counterpart to the rule above, and the one exception to it. A birthday
 * is the 14th of March everywhere on earth: it is not an instant, and storing
 * it as `timestamptz` would shift it to the 13th for anyone who travels, or
 * for a server in a different region than the one that wrote it.
 *
 * `date` and `timestamptz` are both correct, for different questions. "When
 * did this happen" is an instant. "Whose birthday is this" is a date on a
 * calendar. Conflating them is how an app wishes somebody a happy birthday a
 * day early, every year, for one half of its users.
 *
 * Pair with a precision column where the date may be partially known — a
 * scanned photograph often gives a year and nothing more.
 */
export function calendarDate(name: string) {
  return date(name, { mode: 'string' });
}

// ─── Tenant scope ────────────────────────────────────────────────────────────

/**
 * The scope column — what row-level security keys on.
 *
 * Any table holding user data carries `vault_id`, and an RLS policy on that
 * table compares it against the actor set for the transaction. **A table with
 * this column and no policy is a silent hole**, so a CI check enumerates
 * tenant-scoped tables and fails the build when one is missing a policy.
 *
 * Always pair with `scopeIndex()` in the same table definition: every query the
 * application makes filters on it, so without an index every read is a
 * sequential scan of another family's rows as well as your own.
 */
export function vaultScope(name = 'vault_id') {
  return uuidRef(name).notNull();
}

/** The index that must accompany every scope column. */
export function scopeIndex(table: string, column: AnyPgColumn) {
  return index(`ix_${table}_scope`).on(column);
}

// ─── Enumerations ────────────────────────────────────────────────────────────

/**
 * A domain enum, as `varchar` + a `CHECK` constraint rather than a native
 * PostgreSQL enum type.
 *
 * PostgreSQL enums exist and `ADD VALUE` is cheap — but **a value can never be
 * removed from one**, and the type cannot be altered inside a transaction in
 * every case. A `CHECK` constraint can be dropped and re-added in a single
 * migration, which is what you want the first time a state turns out to be
 * wrong.
 *
 * The values come from the Zod enums in `src/shared`, never retyped here, so
 * the database constraint and the TypeScript union cannot drift into a bug that
 * appears only at runtime on real data.
 */
export function enumColumn<T extends readonly string[]>(
  name: string,
  values: T,
) {
  const longest = values.reduce((max, v) => Math.max(max, v.length), 0);
  return varchar(name, { length: Math.max(longest, 16) });
}

/** The SQL fragment for the matching CHECK constraint. */
export function enumCheck(column: string, values: readonly string[]): string {
  const list = values.map((v) => `'${v}'`).join(', ');
  return `"${column}" IN (${list})`;
}

/**
 * The CHECK for a column holding an ARRAY of enum values.
 *
 * `<@` is "is contained by", so the constraint reads: every element of this
 * array must appear in the allowed set. It also passes for an empty array,
 * which is correct — "notify me on no channels" is a real choice.
 */
export function enumArrayCheck(
  column: string,
  values: readonly string[],
): string {
  const list = values.map((v) => `'${v}'`).join(', ');
  return `"${column}" <@ ARRAY[${list}]::text[]`;
}
// ─── Tokens ──────────────────────────────────────────────────────────────────

/**
 * An opaque token — a capsule unlock link, a share link, a session.
 *
 * Never derived from a primary key. Ids are time-ordered by design, so a token
 * derived from one would be guessable from a neighbouring token, and a
 * guessable unlock link is a privacy incident rather than a defect.
 *
 * Stored hashed, never raw: a database backup that leaks must not hand over
 * working links to every sealed capsule.
 *
 * PostgreSQL compares case-sensitively by default, so unlike MySQL this needs
 * no special collation — worth knowing, because adding a case-insensitive
 * collation here later would quietly collapse the keyspace.
 */
export function opaqueToken(name: string, length = 64) {
  // Nullability is the caller’s to decide: a session token is required, an
  // unsent invitation token is not. `.notNull()` at the call site.
  return varchar(name, { length });
}
